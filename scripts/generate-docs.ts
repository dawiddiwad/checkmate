import { readFile, writeFile } from 'node:fs/promises'
import assert from 'node:assert/strict'
import { liteSchema } from '../plugin/src/guide.ts'

const path = new URL('../docs/reference/payloads.md', import.meta.url)
const begin = '<!-- lite payloads: generated by npm run generate from plugin/contracts/lite-*.schema.json -->'
const end = '<!-- end of lite payloads -->'

const escaped = (text: string) => text.replace(/</g, '\\<').replace(/\|/g, '\\|')

function section(title: string, name: 'lite-checklist' | 'lite-record', command: string) {
	const schema = liteSchema(name)
	return [
		`## ${title}`,
		'',
		`QA sends it to \`${command}\`. ${escaped(schema.about)}`,
		'',
		'| Field | Type | Required | Description |',
		'| --- | --- | --- | --- |',
		...schema.fields.map(
			(field) =>
				`| \`${field.path}\` | ${escaped(field.type.replace(/\|/g, ', '))} | ${field.required ? 'yes' : 'no'} | ${escaped(field.description)} |`
		),
		'',
		'```json',
		JSON.stringify(schema.example, null, '\t'),
		'```',
	].join('\n')
}

const generated = [
	begin,
	'',
	section('Lite checklist', 'lite-checklist', 'lite checklist <planId> --target <targetId@revision>'),
	'',
	section('Lite record', 'lite-record', 'lite record <planId> --build <build>'),
	'',
	end,
].join('\n')

const text = await readFile(path, 'utf8')
const from = text.indexOf(begin)
const to = text.indexOf(end)
assert(from >= 0 && to > from, `${path.pathname} needs the lite payloads markers`)
const { format, resolveConfig } = await import('prettier')
const options = await resolveConfig(path)
const next = await format(text.slice(0, from) + generated + text.slice(to + end.length), {
	...options,
	parser: 'markdown',
})
if (process.argv.includes('--check')) assert.equal(text, next, 'Run npm run generate')
else await writeFile(path, next)
