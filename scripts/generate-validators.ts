// Generates plugin/src/validators.js from the JSON Schemas.
// The installed plugin has no npm dependencies. Ajv compiles each schema to
// standalone code, and esbuild bundles the few Ajv runtime helpers into the file.
import { Ajv } from 'ajv'
import addFormats from 'ajv-formats'
import standaloneCode from 'ajv/dist/standalone/index.js'
import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import assert from 'node:assert/strict'

const contracts = new URL('../plugin/contracts/', import.meta.url)
const output = new URL('../plugin/src/validators.js', import.meta.url)
const declarations = new URL('../plugin/src/validators.d.ts', import.meta.url)
const names = [
	'profile',
	'plan',
	'setup-request',
	'plan-request',
	'revise-request',
	'execute-request',
	'report-request',
	'observation',
	'result',
	'response',
]

const ajv = new Ajv({ allErrors: true, code: { source: true, esm: true } })
addFormats.default(ajv)
const exports: Record<string, string> = {}
for (const name of names) {
	const schema = JSON.parse(await readFile(new URL(`${name}.schema.json`, contracts), 'utf8'))
	ajv.addSchema(schema, name)
	exports[name.replace(/-./g, (match) => match[1].toUpperCase())] = name
}

// A plan candidate is a plan without coverage. save-plan calculates coverage.
const plan = JSON.parse(await readFile(new URL('plan.schema.json', contracts), 'utf8'))
delete plan.properties.coverage
plan.required = plan.required.filter((key: string) => key !== 'coverage')
ajv.addSchema(plan, 'plan-candidate')
exports.planCandidate = 'plan-candidate'

const bundle = await build({
	stdin: {
		contents: standaloneCode.default(ajv, exports),
		resolveDir: fileURLToPath(new URL('..', import.meta.url)),
		loader: 'js',
	},
	bundle: true,
	format: 'esm',
	platform: 'node',
	legalComments: 'none',
	minify: true,
	write: false,
})
const header = '// Generated by scripts/generate-validators.ts. Do not edit.\n'
const files = [
	{ path: output, text: header + bundle.outputFiles[0].text },
	{
		path: declarations,
		text:
			header +
			'export type Validator = ((value: unknown) => boolean) & {\n' +
			'\terrors?: Array<{ instancePath: string; message?: string }> | null\n' +
			'}\n' +
			Object.keys(exports)
				.sort()
				.map((name) => `export const ${name}: Validator\n`)
				.join(''),
	},
]
for (const file of files) {
	if (process.argv.includes('--check'))
		assert.equal(await readFile(file.path, 'utf8'), file.text, 'Run node scripts/generate-validators.ts')
	else await writeFile(file.path, file.text)
}
